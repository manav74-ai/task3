linear_pred = linear_model.predict(X_test)

# 2. Decision Tree Regressor
tree_model = DecisionTreeRegressor(random_state=random_seed)
tree_model.fit(X_train, y_train)
tree_pred = tree_model.predict(X_test)

# 3. Random Forest Regressor
forest_model = RandomForestRegressor(random_state=random_seed)
forest_model.fit(X_train, y_train)
forest_pred = forest_model.predict(X_test)

# 4. XGBoost Regressor
xgb_model = XGBRegressor(random_state=random_seed)
xgb_model.fit(X_train, y_train)
xgb_pred = xgb_model.predict(X_test)

# Evaluation Metrics Function
def evaluate_model(y_true, y_pred):
    rmse = mean_squared_error(y_true, y_pred, squared=False)
    mae = mean_absolute_error(y_true, y_pred)
    return rmse, mae

# Evaluate models
models_performance = {
    'Linear Regression': evaluate_model(y_test, linear_pred),
    'Decision Tree': evaluate_model(y_test, tree_pred),
    'Random Forest': evaluate_model(y_test, forest_pred),
    'XGBoost': evaluate_model(y_test, xgb_pred),
}

# Display results in a score table format
score_table = pd.DataFrame(models_performance).T
