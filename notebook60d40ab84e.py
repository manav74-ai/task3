from sklearn.model_selection import train_test_split

random_seed = 42

def train_test_split_equal(df, test_size=0.2):
    df = df.sample(frac=1, random_state=random_seed).reset_index(drop=True)
    train_df, test_df = train_test_split(df, test_size=test_size, random_state=random_seed)
    return train_df, test_df

train_df, test_df = train_test_split_equal(df)

print("Training set size:", len(train_df))
print("Test set size:", len(test_df))

# Preprocessing - Handling Missing Values (if any)
# Example: Fill missing values with median for numerical columns (modify as needed)
for column in train_df.columns:
    if train_df[column].isnull().any():
        if train_df[column].dtype == 'object':
            train_df[column].fillna(train_df[column].mode()[0], inplace=True)
        else:
            train_df[column].fillna(train_df[column].median(), inplace=True)

# Feature Engineering - Convert categorical variables to numerical
train_df = pd.get_dummies(train_df, drop_first=True)
test_df = pd.get_dummies(test_df, drop_first=True)

# Align the columns of train and test sets to ensure they match after one-hot encoding
train_df, test_df = train_df.align(test_df, join='left', axis=1, fill_value=0)

# Scaling features
scaler = StandardScaler()
X_train = scaler.fit_transform(train_df.drop('price', axis=1))
y_train = train_df['price']
X_test = scaler.transform(test_df.drop('price', axis=1))
y_test = test_df['price']

# Modeling - Implementing Algorithms

# 1. Linear Regression
linear_model = LinearRegression()
